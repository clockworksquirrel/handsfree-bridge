"""Copy this task's artifacts without overwriting originals or collecting live grants."""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import shutil
import tempfile


PROJECT = Path("[WORKSPACE_ROOT]")
DESTINATION = Path("[PRIVATE_BUNDLE_ROOT]")
MAPPINGS = [
    (PROJECT / "work/approval-broker-fix", Path("work/approval-broker-fix")),
    (PROJECT / "work/deepapi-source-minimum", Path("work/deepapi-source-minimum")),
    (PROJECT / "work/applescript-research", Path("work/applescript-research")),
    (PROJECT / "output/approval-broker-assessment-archived.md", Path("history/initial-feasibility-report.md")),
    (PROJECT / "output/Accessibility Approval", Path("history/interim-bundle")),
]


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def remove_billing(value):
    if isinstance(value, dict):
        return {key: remove_billing(item) for key, item in value.items() if key not in {"balance", "debitMicrousd"}}
    if isinstance(value, list):
        return [remove_billing(item) for item in value]
    return value


if DESTINATION.exists():
    raise SystemExit("The requested folder already exists; refusing to overwrite it.")
for source, _ in MAPPINGS:
    if not source.exists():
        raise SystemExit(f"Missing task artifact: {source}")
    if DESTINATION.resolve().is_relative_to(source.resolve()):
        raise SystemExit("The destination must not be inside a copied source.")

stage = Path(tempfile.mkdtemp(prefix=".Accessibility-Approval-", dir=DESTINATION.parent))
records = []
excluded = []
used = set()


def copy_one(source: Path, relative: Path):
    if source.is_symlink():
        excluded.append({"source": str(source), "reason": "Symlink not followed."})
        return
    if source.suffix == ".pyc" or "__pycache__" in source.parts or source.name.endswith(".lock"):
        excluded.append({"source": str(source), "reason": "Generated bytecode or transient workflow lock; source and completed state are included."})
        return
    original = source.read_bytes()
    content = original
    notes = []
    if source.name == "scout-state.json":
        raw = json.loads(original)
        cleaned = remove_billing(raw)
        for key, question in raw["questions"].items():
            assert question["response"]["output"] == cleaned["questions"][key]["response"]["output"]
            assert question["requestId"] == cleaned["questions"][key]["requestId"]
        content = (json.dumps(cleaned, indent=2, ensure_ascii=False) + "\n").encode()
        notes.append("Removed account balances and debit amounts; complete research outputs, source arrays, request IDs, and statuses unchanged.")
    elif "private-source-cache" in source.parts and source.suffix == ".json":
        raw = remove_billing(json.loads(original))
        for result in raw.get("results", []):
            for page in result["response"].get("output") or []:
                omitted = {}
                for field in ("markdown", "text"):
                    if isinstance(page.get(field), str):
                        text = page.pop(field)
                        omitted[field] = {"characters": len(text), "sha256": sha(text.encode())}
                page["omittedSourceText"] = omitted
                page["sourceTextPolicy"] = "Full third-party documentation is not redistributed; use the source URL and authored research report."
        content = (json.dumps(raw, indent=2, ensure_ascii=False) + "\n").encode()
        relative = relative.with_name(relative.stem + ".metadata.json")
        notes.append("Metadata counterpart: omitted full third-party page text and account/billing details; retained URLs, titles, response status, request ID, content lengths and hashes.")
    if relative in used:
        raise RuntimeError(f"Destination collision: {relative}")
    used.add(relative)
    target = stage / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    if notes:
        target.write_bytes(content)
        target.chmod(0o600)
    else:
        shutil.copy2(source, target)
    actual = target.read_bytes()
    if actual != content:
        raise RuntimeError(f"Copy verification failed: {relative}")
    records.append({"source": str(source), "destination": relative.as_posix(), "sourceSha256": sha(original),
                    "destinationSha256": sha(actual), "bytes": len(actual),
                    "verification": "expected_sanitization" if notes else "byte_identical", "notes": notes})


for source, relative in MAPPINGS:
    if source.is_file():
        copy_one(source, relative)
        continue
    for directory, names, files in os.walk(source, followlinks=False):
        for name in list(names):
            candidate = Path(directory) / name
            if candidate.is_symlink():
                excluded.append({"source": str(candidate), "reason": "Symlink directory not followed."})
                names.remove(name)
        for name in sorted(files):
            path = Path(directory) / name
            copy_one(path, relative / path.relative_to(source))

copy_one(PROJECT / "work/approval-broker-fix/DELIVERY_README.md", Path("README.md"))
copy_one(PROJECT / "work/approval-broker-fix/COMPLETED_REPORT.md", Path("FINAL_REPORT.md"))

inventory = {"status": "verified", "destination": str(DESTINATION), "originalsPreserved": True,
             "liveCredentialOrGrantStoresCollected": False, "copiedFiles": len(records),
             "byteIdenticalFiles": sum(r["verification"] == "byte_identical" for r in records),
             "sanitizedFiles": sum(r["verification"] == "expected_sanitization" for r in records),
             "files": records, "excluded": excluded,
             "inventoryNote": "This generated inventory does not checksum itself. All other delivered files have verified expected bytes."}
(stage / "INVENTORY.json").write_text(json.dumps(inventory, indent=2, ensure_ascii=False) + "\n")
assert json.loads((stage / "INVENTORY.json").read_text())["copiedFiles"] == len(records)
if DESTINATION.exists():
    raise RuntimeError("A destination appeared during preparation; verified staging folder retained at " + str(stage))
os.rename(stage, DESTINATION)
for record in records:
    assert sha((DESTINATION / record["destination"]).read_bytes()) == record["destinationSha256"]
print(json.dumps({"status": "delivered", "folder": str(DESTINATION), "entryPoint": str(DESTINATION / "README.md"),
                  "copiedFiles": len(records), "byteIdenticalFiles": inventory["byteIdenticalFiles"],
                  "sanitizedFiles": inventory["sanitizedFiles"], "excludedEntries": len(excluded),
                  "allCopiesVerified": True, "originalsPreserved": True}, indent=2))
